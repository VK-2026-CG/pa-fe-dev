import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';

const manifestPath = resolve('public/spec-assets/MY/manifest.json');
if (!existsSync(manifestPath)) throw new Error('public/spec-assets/MY/manifest.json is missing; run immutable Spec sync');
const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
const entries = manifest.assets.map((asset) => [asset.assetId, {
  src: `/spec-assets/MY/${asset.file}`,
  type: asset.type,
  mediaType: asset.mediaType,
  sha256: asset.sha256,
  sourceStatus: asset.sourceStatus,
  intrinsic: asset.intrinsic,
  rendering: asset.rendering,
  accessibility: asset.accessibility,
}]);
writeFileSync(resolve('src/generated/spec-assets.ts'), `/* Generated by scripts/generate-spec-assets.mjs; do not edit. */\nexport const specAssets = ${JSON.stringify(Object.fromEntries(entries), null, 2)} as const;\nexport type SpecAssetId = keyof typeof specAssets;\n`);
console.log(`Generated ${entries.length} typed Spec assets.`);